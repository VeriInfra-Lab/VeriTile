"""Replay a dot bundle and export a source-specific candidate/evidence table.

Only eligible passing evidence enters `all`; rejection is retained as data.
The Lean table never constructs the external EvidenceValidated premise.
"""
import argparse
from datetime import datetime, timezone
import json
import math
from pathlib import Path

if __package__:
    from . import two_gates_dot as dot
else:
    import two_gates_dot as dot

ROOT=dot.ROOT
REPORT=ROOT/'experiments/floating_point/dot/report/receipt.json'
OUTPUT=ROOT/'VeriTile/Triton/Float/DotAdmission.lean'


def instance_key(manifest,report):
    return 'dot:'+dot.digest({'manifest':manifest,'lowerings':report['lowerings']})


def validate(receipt):
    m,r=receipt['manifest'],receipt['report']
    expected=dot.plan(False,2**32)
    if (receipt['kind']!='dot_contraction_receipt' or m['format']!=dot.FORMAT or
            any(m.get(key)!=value for key,value in expected.items()) or
            r['complete'] is not True or r['rule']!='DOT-ADD-TO-DOTACC' or
            r['manifest_sha256']!=dot.digest(m) or r['source_hashes']!=m['sources'] or
            r['backend']!=m['backend'] or receipt['instance_key']!=instance_key(m,r)):
        raise ValueError('dot receipt identity, precision, fixed budget or scope differs')
    result=r['result'];s=result['sampling'];b=result['bias'];v=result['magnitude']
    if (s['drawn']!=2**32 or s['peak_drawn']!=2**32 or
            s['valid']!=s['peak_valid'] or not 2<=s['valid']<=s['in_domain']<=s['drawn'] or
            s['excluded_domain']!=s['drawn']-s['in_domain'] or
            s['excluded_nonfinite']!=s['in_domain']-s['valid'] or
            r['raw_audits_verified']!=len(dot.audit_indices(m)) or
            r['part_statistics_verified']!=len(dot.part_counts(m))):
        raise ValueError('dot receipt group counts or required audit coverage differs')
    strata=b['strata']
    if (len(strata)!=1 or strata[0]['probability']!=1. or strata[0]['n']!=s['valid'] or
            strata[0]['mean']!=b['mean'] or strata[0]['m2']<0 or
            not math.isclose(math.sqrt(strata[0]['m2']/(s['valid']-1)/s['valid']),
                             b['standard_error'],rel_tol=1e-14,abs_tol=1e-15)):
        raise ValueError('dot standard error differs from independent group moments')
    bound=abs(b['mean'])+m['settings']['bias_se_multiplier']*b['standard_error']
    if (not all(math.isfinite(x) for x in [b['mean'],b['standard_error'],b['upper'],v['reference_peak'],v['candidate_peak']]) or
            b['standard_error']<0 or min(v['reference_peak'],v['candidate_peak'])<0 or
            not math.isclose(bound,b['upper'],rel_tol=1e-14,abs_tol=1e-15) or
            b['tolerance']!=m['settings']['bias_tolerance_ulp'] or v['limit']!=m['settings']['peak_ratio_limit']):
        raise ValueError('dot gate statistics or thresholds differ')
    bp=bound<=b['tolerance'];vp=v['candidate_peak']<=v['limit']*v['reference_peak']
    ratio=0. if v['candidate_peak']==0 else v['candidate_peak']/v['reference_peak'] if v['reference_peak'] else '+inf'
    decision='ACCEPT' if bp and vp else 'REJECT'
    eligible=decision=='ACCEPT' and r['special']['classification_mismatches']==0 and r['special']['nan_payload_differences']==0
    if (b['status']!=('PASS' if bp else 'FAIL') or v['status']!=('PASS' if vp else 'FAIL') or
            result['decision']!=decision or r['all_words_admission_eligible']!=eligible or v['ratio']!=ratio):
        raise ValueError('dot decision or admission contradicts recorded gates/scope')
    return eligible


def render(receipt):
    eligible=validate(receipt);m,r=receipt['manifest'],receipt['report']
    quote=lambda x:json.dumps(x,ensure_ascii=True)
    configuration={'profile':m['profile'],'settings':m['settings'],'backend':m['backend'],
        'seeds':m['seeds'],'formal_domain':m['formal_domain'],'probe_domain':m['probe_domain'],
        'manifest_sha256':r['manifest_sha256'],'sources':m['sources'],'lowerings':r['lowerings'],
        'decision':r['result']['decision'],'special':r['special']}
    artifact='experiments/floating_point/dot/report/receipt.json#'+receipt['instance_key']
    bias='pass' if r['result']['bias']['status']=='PASS' else 'fail'
    peak='pass' if r['result']['magnitude']['status']=='PASS' else 'fail'
    lines=['/- Generated by scripts/export_dot_rules.py after independent CPU bundle replay.',
        '   Numerical evidence is data; external validation remains a scoped premise. -/',
        'import VeriTile.Triton.Float.DotContraction','',
        'namespace VeriTile.Triton.FP.DotAdmission','',
        f'def instanceKey : String := {quote(receipt["instance_key"])}',
        'def configuration : Lean.Json :=',
        f'  (Lean.Json.parse {quote(dot.common.registry.canonical_json(configuration).decode())}).toOption.getD .null','',
        'def contract : Spec.Contract where',
        '  ruleID := "DOT-ADD-TO-DOTACC"','  instanceKey := instanceKey',
        '  configuration := configuration','  warningPolicy := .passOnly',
        '  description := "Local FP32 K32 TF32 separate dot/add versus seeded dot; actual backend and numerical outcome are recorded."','',
        'def evidence : Spec.Evidence where','  instanceKey := instanceKey',
        f'  artifact := some {quote(artifact)}',f'  bias := .{bias}',f'  vars := .{peak}','',
        'def candidate : Spec.RuleEntry ComputeStmt := DotContraction.entry contract evidence','',
        f'def eligible : Bool := {str(eligible).lower()}',
        'def all : List (Spec.RuleEntry ComputeStmt) := '+('[candidate]' if eligible else '[]'),
        f'theorem available_count : all.length = {1 if eligible else 0} := rfl','']
    if eligible:
        lines += ['theorem admit (validation : Spec.EvidenceValidated candidate.rule candidate.evidence) :',
                  '    Spec.AcceptedAtom candidate :=',
                  '  ⟨validation, rfl, rfl, ⟨rfl, rfl⟩⟩','']
    elif bias=='fail' or peak=='fail':
        lines += ['theorem policy_rejects : ¬ Spec.PolicyAllows .passOnly evidence := by',
                  '  intro policy',
                  '  have impossible : false = true := policy.'+('1' if bias=='fail' else '2'),
                  '  cases impossible','']
    lines += ['end VeriTile.Triton.FP.DotAdmission','']
    return '\n'.join(lines)


def collect(bundle):
    report=dot.replay(bundle);manifest=json.loads((bundle/'manifest.json').read_text())
    record=json.loads((bundle/'record.json').read_text())
    receipt={'kind':'dot_contraction_receipt','checked_at_utc':datetime.now(timezone.utc).isoformat(),
             'manifest':manifest,'report':report,'instance_key':instance_key(manifest,report),
             'record_sha256':dot.file_hash(bundle/'record.json'),
             'measurement':{key:record[key] for key in ['elapsed_seconds','peak_cuda_allocated_bytes','peak_cuda_reserved_bytes']},
             'trust':'Independent CPU consistency/oracle/audit replay; remote GPU execution remains trusted.'}
    validate(receipt)
    return receipt


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--bundle',type=Path)
    p.add_argument('--receipt',type=Path,default=REPORT);p.add_argument('--output',type=Path,default=OUTPUT)
    p.add_argument('--check',action='store_true');a=p.parse_args(argv)
    if a.check and a.bundle:p.error('--check uses the saved compact receipt')
    receipt=collect(a.bundle) if a.bundle else json.loads(a.receipt.read_text())
    content=render(receipt)
    if a.check:
        if a.output.read_text()!=content:raise ValueError('generated dot evidence table is stale')
    else:
        if a.bundle:
            a.receipt.parent.mkdir(parents=True,exist_ok=True)
            with a.receipt.open('x') as f:json.dump(receipt,f,indent=2,allow_nan=False);f.write('\n')
        a.output.write_text(content)
    print(json.dumps({'eligible':validate(receipt),'decision':receipt['report']['result']['decision'],
                      'output':str(a.output),'checked':a.check}))
    return 0


if __name__=='__main__':raise SystemExit(main())
