class StridedBuffer:
    """A drop-in replacement of torch.Tensor that can be used in wrapper generated by
    PointwiseDynamicFunction. It allows us to use a different shape, stride, data
    pointer that that of the base tensor.

    It is a kind of reinterpretation of the base tensor. We make this class since we
    cannot get a Tensor view with negative strides via torch APIs, while we need this
    to implement flip op.

    Although generated code can accept torch.Tensor & StridedBuffer, but StridedBuffer
    may not have all the methods as torch.Tensors do. We add some attributes & methods
    with the same name as torch.Tensor, which are used in the generated code. But we
    may not cover all the methods, add one if what you need is missing here.

    And can also be used in triton kernels since it also has dtype & data_ptr().
    """

    def __init__(
        self, base: torch.Tensor, shape=None, strides=None, dtype=None, offset=0
    ):
        self._base = base
        self.dtype = dtype or base.dtype
        if offset == 0:
            self._data_ptr = self._base.data_ptr()
        else:
            offset = self.dtype.itemsize * offset
            self._data_ptr = self._base.data_ptr() + offset
        self.shape = tuple(shape if shape is not None else self._base.shape)
        self._strides = tuple(strides if strides is not None else self._base.stride())
        self.device = self._base.device
        self.ndim = len(self.shape)

    def stride(self):
        return self._strides

    def size(self):
        return self.shape

    def element_size(self):
        return self.dtype.itemsize

    def numel(self):
        return math.prod(self.shape)

    def dim(self):
        return self.ndim

    def unwrap(self):
        return self._base

    def data_ptr(self):
        return self._data_ptr

@triton.jit
def isfinite_func(x):
    return _isfinited(x) if x.dtype.is_fp64() else _finitef(x.to(tl.float32))


CHUNK_SIZE = 1 << 30
BLOCK_SIZE = 1024


def _checked_view(value, *, output):
    if not isinstance(value, (torch.Tensor, StridedBuffer)):
        raise TypeError("operands must be Tensor or StridedBuffer")
    raw_view = isinstance(value, StridedBuffer)
    base = value.unwrap() if raw_view else value
    if not isinstance(base, torch.Tensor):
        raise TypeError("StridedBuffer base must be a Tensor")
    if base.layout != torch.strided:
        raise ValueError("base must use strided layout")
    if (value.dtype != torch.bool if output else value.dtype not in (torch.float32, torch.float64)):
        raise TypeError("isfinite requires FP32/FP64 input and bool output views")
    if value.device.type != "cuda" or base.device != value.device:
        raise ValueError("view and base must share a CUDA device")
    if not raw_view and base.is_neg():
        raise ValueError("Tensor operands must not carry a lazy negative flag")
    shape, strides = tuple(value.shape), tuple(value.stride())
    if len(shape) != 1 or len(strides) != 1:
        raise ValueError("operands must have rank one")
    n, stride = shape[0], strides[0]
    if type(n) is not int or type(stride) is not int or n < 0:
        raise TypeError("shape must be a nonnegative integer and stride an integer")
    if not -(1 << 63) <= stride < (1 << 63):
        raise ValueError("stride must fit signed int64")
    pointer, width = value.data_ptr(), value.element_size()
    if type(pointer) is not int:
        raise TypeError("data pointer must be a Python integer")
    if n:
        storage = base.untyped_storage()
        lo, capacity = storage.data_ptr(), storage.nbytes()
        last = pointer + (n - 1) * stride * width
        if pointer % width:
            raise ValueError("view pointer must have natural element alignment")
        if min(pointer, last) < lo or max(pointer, last) + width > lo + capacity:
            raise ValueError("view accesses must remain inside backing storage")
        if not 0 <= lo <= lo + capacity <= (1 << 64):
            raise ValueError("backing storage must fit native address space")
    return n, stride, pointer, width


def _contains(start, stride, n, address):
    if stride == 0:
        return n > 0 and address == start
    delta = address - start
    return delta % stride == 0 and 0 <= delta // stride < n


def _disjoint(x, sx, width, y, sy, n):
    if n == 0:
        return True
    xlast, ylast = x + (n - 1) * sx * width, y + (n - 1) * sy
    if max(x, xlast) + width <= min(y, ylast) or max(y, ylast) < min(x, xlast):
        return True
    return all(not _contains(y, sy, n, x + i * sx * width + byte)
               for i in range(n) for byte in range(width))


def _slice(value, start, count, stride):
    base = value.unwrap() if isinstance(value, StridedBuffer) else value
    result = StridedBuffer(base, shape=(count,), strides=(stride,), dtype=value.dtype)
    result._data_ptr = value.data_ptr() + start * stride * value.element_size()
    return result


@triton.jit
def isfinite_strided_chunk(in0_ptr, out0_ptr, in0_stride, out0_stride, n,
                           BLOCK_SIZE: tl.constexpr):
    pid = tl.program_id(0)
    offsets = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n
    indices = offsets.to(tl.int64)
    in0 = tl.load(in0_ptr + indices * tl.cast(in0_stride, tl.int64), mask=mask).to(in0_ptr.type.element_ty)
    out0 = isfinite_func(in0)
    tl.store(out0_ptr + indices * tl.cast(out0_stride, tl.int64),
             out0.to(out0_ptr.type.element_ty), mask=mask)


@triton.jit
def isfinite_strided_chunk_index_commuted(in0_ptr, out0_ptr, in0_stride, out0_stride, n,
                           BLOCK_SIZE: tl.constexpr):
    pid = tl.program_id(0)
    offsets = BLOCK_SIZE * pid + tl.arange(0, BLOCK_SIZE)
    mask = offsets < n
    indices = offsets.to(tl.int64)
    in0 = tl.load(in0_ptr + indices * tl.cast(in0_stride, tl.int64), mask=mask).to(in0_ptr.type.element_ty)
    out0 = isfinite_func(in0)
    tl.store(out0_ptr + indices * tl.cast(out0_stride, tl.int64),
             out0.to(out0_ptr.type.element_ty), mask=mask)


def isfinite_func_wrapper_rank_1_repaired(in0, /, *, out0):
    n, sx, xp, width = _checked_view(in0, output=False)
    ny, sy, yp, _ = _checked_view(out0, output=True)
    if n != ny:
        raise ValueError("operand shapes mismatch")
    if in0.device != out0.device:
        raise ValueError("operands must share a CUDA device")
    if n and sy == 0:
        raise ValueError("nonempty output stride must be nonzero")
    if not _disjoint(xp, sx, width, yp, sy, n):
        raise ValueError("input and output accessed byte footprints must be disjoint")
    if n == 0:
        return out0
    with torch.cuda._DeviceGuard(in0.device.index):
        for start in range(0, n, CHUNK_SIZE):
            count = min(CHUNK_SIZE, n - start)
            isfinite_strided_chunk[(triton.cdiv(count, BLOCK_SIZE),)](
                _slice(in0, start, count, sx), _slice(out0, start, count, sy),
                sx, sy, count, BLOCK_SIZE=BLOCK_SIZE)
    return out0

