"""Checked nonempty FP32 rank-one ReLU with both signed stride directions.

StridedBuffer, heuristics and kernels are unchanged. Views are bounded and
accessed footprints are disjoint; input stride zero and disjoint views sharing
one allocation are supported. The exact caller-provided out0 is returned.
"""

import math
from typing import Union
import torch
import triton
from triton import language as tl

def heuristics_for_tile_size(max_tile_size, *sizes):
    ndim = len(sizes)
    tile_sizes = [0 for _ in range(ndim)]
    for i in range(ndim):
        size = sizes[ndim - 1 - i]
        tile_size = min(max_tile_size, triton.next_power_of_2(size))
        tile_sizes[ndim - 1 - i] = tile_size
        max_tile_size = max(1, max_tile_size // tile_size)
    return tuple(tile_sizes)

def heuristics_for_num_warps(tile_size):
    if tile_size < 2048:
        return 4
    elif tile_size < 4096:
        return 8
    else:
        return 16
    

class StridedBuffer:
    """A drop-in replacement of torch.Tensor that can be used in wrapper generated by
    PointwiseDynamicFunction. It allows us to use a different shape, stride, data
    pointer that that of the base tensor.

    It is a kind of reinterpretation of the base tensor. We make this class since we
    cannot get a Tensor view with negative strides via torch APIs, while we need this
    to implement flip op.

    Although generated code can accept torch.Tensor & StridedBuffer, but StridedBuffer
    may not have all the methods as torch.Tensors do. We add some attributes & methods
    with the same name as torch.Tensor, which are used in the generated code. But we
    may not cover all the methods, add one if what you need is missing here.

    And can also be used in triton kernels since it also has dtype & data_ptr().
    """

    def __init__(
        self, base: torch.Tensor, shape=None, strides=None, dtype=None, offset=0
    ):
        self._base = base
        self.dtype = dtype or base.dtype
        if offset == 0:
            self._data_ptr = self._base.data_ptr()
        else:
            offset = self.dtype.itemsize * offset
            self._data_ptr = self._base.data_ptr() + offset
        self.shape = tuple(shape if shape is not None else self._base.shape)
        self._strides = tuple(strides if strides is not None else self._base.stride())
        self.device = self._base.device
        self.ndim = len(self.shape)

    def stride(self):
        return self._strides

    def size(self):
        return self.shape

    def element_size(self):
        return self.dtype.itemsize

    def numel(self):
        return math.prod(self.shape)

    def dim(self):
        return self.ndim

    def unwrap(self):
        return self._base

    def data_ptr(self):
        return self._data_ptr



def _checked_view(x):
    if not isinstance(x, (torch.Tensor, StridedBuffer)):
        raise TypeError("operands must be Tensor or StridedBuffer")
    base = x.unwrap() if isinstance(x, StridedBuffer) else x
    if not isinstance(base, torch.Tensor):
        raise TypeError("StridedBuffer base must be a Tensor")
    if base.layout != torch.strided:
        raise TypeError("base must have strided layout")
    if x.dtype != torch.float32 or base.dtype != torch.float32:
        raise TypeError("view and base must have dtype torch.float32")
    if x.device.type != "cuda" or base.device != x.device:
        raise ValueError("view and base must share a CUDA device")
    if base.is_neg():
        raise ValueError("base must not have an unresolved negative view bit")
    shape, strides = tuple(x.shape), tuple(x.stride())
    if len(shape) != 1 or len(strides) != 1:
        raise ValueError("operands must have rank one")
    n, stride = shape[0], strides[0]
    if type(n) is not int or type(stride) is not int:
        raise TypeError("shape and stride must be Python integers")
    if not 0 < n < (1 << 31):
        raise ValueError("length must satisfy 0 < n < 2**31")
    if not -(1 << 63) <= stride < (1 << 63):
        raise ValueError("stride must fit signed int64")
    storage = base.untyped_storage()
    storage_ptr, capacity = storage.data_ptr(), storage.nbytes() // 4
    pointer = x.data_ptr()
    if type(pointer) is not int or storage_ptr % 4 != 0:
        raise ValueError("FP32 storage must be four-byte aligned")
    element_base = (pointer - storage_ptr) // 4
    if pointer != storage_ptr + 4 * element_base:
        raise ValueError("view pointer must select an FP32 storage cell")
    last = element_base + (n - 1) * stride
    if min(element_base, last) < 0 or max(element_base, last) >= capacity:
        raise ValueError("view accesses must stay within the backing storage")
    return n, stride, pointer // 4


def _contains_cell(start, stride, n, address):
    # Output stride has already been checked nonzero. Division is used only
    # after exact divisibility, so both signs have the same integer quotient.
    delta = address - start
    return delta % stride == 0 and 0 <= delta // stride < n


def _footprints_disjoint(x_start, sx, y_start, sy, n):
    x_last, y_last = x_start + (n - 1) * sx, y_start + (n - 1) * sy
    if max(x_start, x_last) < min(y_start, y_last) or max(y_start, y_last) < min(x_start, x_last):
        return True
    # Exact arithmetic-progression membership; same-allocation interleaved
    # disjoint views remain admitted. No storage-sized temporary is allocated.
    return all(not _contains_cell(y_start, sy, n, x_start + i * sx) for i in range(n))


def relu_forward_wrapper_rank_1(in0: Union[torch.Tensor, StridedBuffer], /, *, out0: Union[torch.Tensor, StridedBuffer]): 
    """Generated wrapper function with Pointwise: StridedBuffer, StridedBuffer(a1!) -> StridedBuffer(a1!)"""
    nx, sx, x_start = _checked_view(in0)
    ny, sy, y_start = _checked_view(out0)
    if nx != ny:
        raise ValueError("operand shapes mismatch")
    if in0.device != out0.device:
        raise ValueError("operands must share a CUDA device")
    if sy == 0:
        raise ValueError("output stride must be nonzero")
    if not _footprints_disjoint(x_start, sx, y_start, sy, nx):
        raise ValueError("input and output accessed footprints must be disjoint")
    assert in0.shape == out0.shape, 'operand shapes mismatch'
    # task partitioning
    shape = out0.shape
    num_tasks = out0.numel()
    tile_sizes = heuristics_for_tile_size(512, *shape)
    tile_size = math.prod(tile_sizes)
    num_tiles = math.prod(triton.cdiv(size, tile_size) for size, tile_size in zip(shape, tile_sizes))
    num_ctas = min(65536, num_tiles)
    tiles_per_cta = triton.cdiv(num_tiles, num_ctas)
    num_warps = heuristics_for_num_warps(tile_size)
    one_tile_per_cta = tiles_per_cta==1
    grid = (num_ctas, 1, 1)
    # kernel launch
    in0_strides = in0.stride()
    in0_stride_order = (0,)
    out0_strides = out0.stride()
    out0_stride_order = (0,)
    with torch.cuda._DeviceGuard(in0.device.index):
        relu_forward_kernel_rank_1[grid](
            in0, out0,
            in0_strides[0], # stride for in0
            in0_stride_order[0], # stride order for in0
            out0_strides[0], # stride for out0
            out0_stride_order[0], # stride orderfor out0
            shape[0], # task indexing space
            num_tasks, # num tasks
            tiles_per_cta=tiles_per_cta, # tiles_per_cta
            tile_size0=tile_sizes[0],
            one_tile_per_cta=one_tile_per_cta,
            num_warps=num_warps,
        )
    return out0

@triton.jit
def relu_forward(x):
    return tl.where(x > 0, x, 0)

@triton.jit
def relu_forward_kernel_rank_1(
    in0_ptr: tl.tensor, # of tl.pointer_type
    out0_ptr: tl.tensor, # of tl.pointer_type
    in0_stride0: int, # strides for in0
    in0_stride_order0: tl.constexpr, # stride order for in0
    out0_stride0: int, # strides for out0
    out0_stride_order0: tl.constexpr, # stride order for out0
    s0: int, # task_space
    num_tasks: int,
    tiles_per_cta: int,
    tile_size0: tl.constexpr,
    one_tile_per_cta: tl.constexpr,
):
    pid = tl.program_id(0)
    num_tiles0 = tl.cdiv(s0, tile_size0)
    if one_tile_per_cta: # monolitic kernel style
        tile_id = pid
        # pid multi index recontruction: we use c ordering, right axes changes fastest
        tile_id0 = tile_id

        # tile offsets
        offset0 = tile_id0 * tile_size0
        # loads
        in0_bptr = tl.make_block_ptr(in0_ptr, (s0,), (in0_stride0,), (offset0,), (tile_size0,), order=(in0_stride_order0,))
        in0 = tl.load(in0_bptr, boundary_check=(in0_stride_order0,)).to(in0_ptr.type.element_ty) # workaround the bug on bool, we should use the original pointer's dtype(instead of block pointer's)

        # compute
        out0 = relu_forward(in0)

        # stores, note that store to block pointer does not automatically cast the value to the pointer's dtype
        out0_bptr = tl.make_block_ptr(out0_ptr, (s0,), (out0_stride0,), (offset0,), (tile_size0,), order=(out0_stride_order0,))
        tl.store(out0_bptr, out0.to(out0_bptr.type.element_ty), boundary_check=(out0_stride_order0,))
    else: # grid-stride-loop style kernel
        num_ctas = tl.num_programs(0)
        for j in range(0, tiles_per_cta):
            tile_id = pid + j * num_ctas
            # pid multi index recontruction: we use c ordering, right axes changes fastest
            tile_id0 = tile_id

            # tile offsets
            offset0 = tile_id0 * tile_size0
            # loads
            in0_bptr = tl.make_block_ptr(in0_ptr, (s0,), (in0_stride0,), (offset0,), (tile_size0,), order=(in0_stride_order0,))
            in0 = tl.load(in0_bptr, boundary_check=(in0_stride_order0,)).to(in0_ptr.type.element_ty) # workaround the bug on bool, we should use the original pointer's dtype(instead of block pointer's)

            # compute
            out0 = relu_forward(in0)

            # stores, note that store to block pointer does not automatically cast the value to the pointer's dtype
            out0_bptr = tl.make_block_ptr(out0_ptr, (s0,), (out0_stride0,), (offset0,), (tile_size0,), order=(out0_stride_order0,))
            tl.store(out0_bptr, out0.to(out0_bptr.type.element_ty), boundary_check=(out0_stride_order0,))




